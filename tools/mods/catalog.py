#!/usr/bin/env python3
"""catalog.py: TF.NX's mod catalog from mods/<name>/mod.toml (mods/README.md; docs/PLAN-TFNX-2026-11-04.md). In seconds, apart from the
translator (a catalog change needs no retranslation).

  catalog.py            writes hw-probe/exlaunch/source/program/modcatalog.gen.hpp (the module's table) and docs/MODS-CATALOG.md
  catalog.py --check    exit 1 when either is out of date (tools/build-probe.sh runs it)
  catalog.py --folders  one line per mod whose folder our tools build: <folder> <extras 0|1> <mod dir> <build command> (tab-separated)
  catalog.py --checks <name>   its [check]: "with <command>" and "expect <log line>" lines (tools/mods/check.sh)

A mod's name, version and display name come from its own meta.json (mod.toml `meta`, kept in mods/<name>/); the files its folder must
have from `needs`. Only mods/ is read for the outputs, so any checkout builds; a translated mod's `vendored` release, where checked out,
must match its copies (meta.json, every "Content/..." literal of its source in `needs`)."""
import json, os, re, sys, tomllib

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
MODS = os.path.join(ROOT, "mods")
HEADER = os.path.join(ROOT, "hw-probe/exlaunch/source/program/modcatalog.gen.hpp")
DOC = os.path.join(ROOT, "docs/MODS-CATALOG.md")
ATLASES = {"Atlas": 0, "BGAtlas": 1, "MenuAtlas": 2, "BossAtlas": 3}   # FortRise's SubtextureAtlasDestination


def load():
    mods = []
    for d in sorted(os.listdir(MODS)):
        p = os.path.join(MODS, d, "mod.toml")
        if not os.path.isfile(p): continue
        m = tomllib.load(open(p, "rb"))
        meta_path = os.path.normpath(os.path.join(MODS, d, m["meta"]))
        if not os.path.isfile(meta_path): sys.exit(f"catalog: {d}: no meta.json at {meta_path}")
        meta = {k.lower(): v for k, v in json.load(open(meta_path, encoding="utf-8-sig")).items()}
        if meta.get("name") != d: sys.exit(f"catalog: mods/{d}: its meta.json's name is {meta.get('name')!r} (the folder must be named after it)")
        needs = set(m.get("needs", []))
        # a translated mod's vendored release (a submodule: only checked out where the translator runs): its copies here must match it
        vend = os.path.normpath(os.path.join(MODS, d, m["vendored"])) if m.get("vendored") else None
        if vend and os.path.isfile(os.path.join(vend, "meta.json")):
            if open(os.path.join(vend, "meta.json"), "rb").read() != open(meta_path, "rb").read():
                sys.exit(f"catalog: mods/{d}/meta.json differs from {os.path.relpath(vend, ROOT)}/meta.json (copy it over)")
            seen = set()
            for r, _, fs in os.walk(os.path.join(vend, "src")):
                for f in fs:
                    if f.endswith(".cs"):
                        seen.update(re.findall(r'"(Content/[^"{}]+\.[A-Za-z0-9]+)"', open(os.path.join(r, f), encoding="utf-8").read()))
            if seen - needs: sys.exit(f"catalog: mods/{d}: its source reads {sorted(seen - needs)}: add them to `needs`")
        for r in m.get("replaces", []):
            if r.get("atlas", "Atlas") not in ATLASES: sys.exit(f"catalog: {d}: replaces: unknown atlas {r.get('atlas')}")
        mods.append({"dir": d, "toml": m, "meta": meta, "needs": sorted(needs)})
    return mods


def q(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def header(mods):
    out = ["/* GENERATED by tools/mods/catalog.py from mods/<name>/mod.toml: do not edit. TF.NX's catalog mods (modcatalog.hpp). */",
           "#pragma once", '#include "modcatalog.hpp"']
    for m in mods:
        for key in ("boot", "early"):
            f = m["toml"].get(key)
            if f:
                ns, _, fn = f.rpartition("::")
                out.append(f"namespace {ns} {{ void {fn}(); }}" if ns else f"void {fn}();")
    out.append("namespace tfex::mods {")
    rows = []
    for i, m in enumerate(mods):
        t = m["toml"]
        repl = [f'{{ {q(r["id"])}, {q(r["with"])}, {ATLASES[r.get("atlas", "Atlas")]} }}' for r in t.get("replaces", [])]
        out.append(f"inline constexpr const char* kNeeds{i}[] = {{ {', '.join(map(q, m['needs'])) or '{}'} }};")
        out.append(f"inline constexpr const char* kOverlay{i}[] = {{ {', '.join(map(q, t.get('overlay', []))) or '{}'} }};")
        out.append(f"inline constexpr CatalogReplace kReplaces{i}[] = {{ {', '.join(repl) or '{}'} }};")
        fn = lambda k: "&::" + t[k] if t.get(k) else "nullptr"
        rows.append(f"    {{ {q(m['meta']['name'])}, {q(m['meta'].get('displayname', m['meta']['name']))}, {q(m['meta'].get('version', '0.0.0'))}, "
                    f"kNeeds{i}, {len(m['needs'])}, kOverlay{i}, {len(t.get('overlay', []))}, kReplaces{i}, {len(repl)}, {fn('boot')}, {fn('early')} }},")
    out.append("inline constexpr CatalogMod kCatalog[] = {")
    out += rows or ["    { nullptr, nullptr, nullptr, nullptr, 0, nullptr, 0, nullptr, 0, nullptr, nullptr },"]
    out += ["};", f"inline constexpr int kCatalogCount = {len(mods)};", "}  // namespace tfex::mods", ""]
    return "\n".join(out)


def doc(mods):
    lines = ["# TF.NX mod catalog", "",
             "GENERATED by tools/mods/catalog.py from mods/<name>/mod.toml: do not edit. Every code mod whose logic TF.NX carries: its",
             "folder in `sd:/xplay/mods/` (the PC release as is) turns it on and brings its files. A folder with every file below loads",
             "whatever its own version; online, the lobby shows the version TF.NX runs. Content-only mods (archers, skins, towers) need no",
             "entry: they load from their folder as on the PC. How to add a mod: mods/README.md.", "",
             "| mod | name | TF.NX runs | logic | author | permission | works |", "|---|---|---|---|---|---|---|"]
    for m in mods:
        o, mt = m["toml"].get("overview", {}), m["meta"]
        lines.append(f"| {mt.get('displayname', mt['name'])} | `{mt['name']}` | {mt.get('version', '?')} | {m['toml'].get('logic', '?')} | "
                     f"{mt.get('author', '?')} | {o.get('permission', '')} | {o.get('works', '')} |")
    for m in mods:
        o, mt, t = m["toml"].get("overview", {}), m["meta"], m["toml"]
        upd = mt.get("update", {}).get("gamebanana", {}).get("id")
        lines += ["", f"## {mt.get('displayname', mt['name'])} {mt.get('version', '?')}", "",
                  f"- Source: {o.get('source', '')}", f"- Download: {o.get('download', '')}"]
        if upd: lines.append(f"- Updates: GameBanana {upd} (its meta.json's `update`)")
        lines.append("- Files its folder must have: " + (", ".join(f"`{n}`" for n in m["needs"]) or "none"))
        if t.get("replaces"): lines.append("- Replaces while loaded: " + ", ".join(f"`{r['id']}` with its `{r['with']}`" for r in t["replaces"]))
        if t.get("overlay"): lines.append("- Game files its folder supplies: " + ", ".join(f"`{p}`" for p in t["overlay"]))
        if t.get("early"): lines.append(f"- At module start, folder or not: `{t['early']}`")
    return "\n".join(lines) + "\n"


def main():
    mods = load()
    if "--folders" in sys.argv:
        for m in mods:
            f = m["toml"].get("folder", {})
            if f.get("build"): print("\t".join([m["dir"], "1" if f.get("extras") else "0", os.path.join(MODS, m["dir"]), f["build"]]))
        return
    if "--checks" in sys.argv:
        name = sys.argv[sys.argv.index("--checks") + 1]
        m = next((m for m in mods if m["dir"] == name), None)
        if not m: sys.exit(f"catalog: no mods/{name}")
        for c in m["toml"].get("check", {}).get("with", []): print("with", c)
        for e in m["toml"].get("check", {}).get("expect", []): print("expect", e)
        return
    files = {HEADER: header(mods), DOC: doc(mods)}
    if "--check" in sys.argv:
        stale = [os.path.relpath(p, ROOT) for p, t in files.items() if not os.path.isfile(p) or open(p, encoding="utf-8").read() != t]
        print("catalog: " + (f"out of date: {', '.join(stale)}: run tools/mods/catalog.py" if stale else f"up to date ({len(mods)} mods)"))
        sys.exit(1 if stale else 0)
    for p, t in files.items(): open(p, "w", encoding="utf-8").write(t)
    print(f"catalog: {len(mods)} mod(s) -> {os.path.relpath(HEADER, ROOT)}, docs/MODS-CATALOG.md")


main()
