#!/usr/bin/env python3
"""state-fieldcheck.py: the TF.State measurement's runtime check of the private-field offsets (tools/tfex/state-pins.toml and confirmed
translate.toml [pin] entries): class, offset, the PC field's type (towerfall-pc.il) and a kind. tfexgen_state.cpp reads each from the
live entities and logs what is there: a reference field must hold that type (or null); since step D also number fields, whose values
must be plausible (kind: 1 bool 0/1, 2 float32 finite and |x| < 1e7, 3 an int32 enum -16..4095, 4 a Vector2's two floats). Writes hw-probe/.../tfex/runtime/tfexgen_state_fieldcheck.inc."""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
PC_IL = os.path.join(here, '..', '..', '.cache', 'towerfall-pc.il')   # (as tools/re/sigs.py finds it)
if not os.path.exists(PC_IL): PC_IL = os.path.expanduser('~/Code/Towerfall Switch Mods/switch-online/.cache/towerfall-pc.il')
decl = {}
cur = []
for line in open(PC_IL, encoding='utf-8', errors='replace'):
    s = line.strip()
    if s.startswith('.class'):
        name = re.search(r'([\w.`<>]+)\s+extends', s).group(1) if 'extends' in s else s.split()[-1]
        cur.append([name, 0]); decl.setdefault('+'.join(x[0] for x in cur), {}); continue
    if cur and s.startswith('} // end of class'): cur.pop(); continue
    m = re.match(r'\.field\s+(.*?)\s+([\w<>$`]+)\s*$', s)
    if cur and m and ' static ' not in ' ' + m.group(1) + ' ': decl['+'.join(x[0] for x in cur)][m.group(2)] = m.group(1)
enums = {c: f for c, f in decl.items() if list(f) == ['value__']}
rows = []
for f in ('state-pins.toml', 'translate.toml'):
    for m in re.finditer(r'\[pin\."([\w.+`]+)\.(\w+)\(\)"\]\s*off = (0x[0-9a-f]+)', open(os.path.join(here, f)).read()):
        cls, fld, off = m.group(1), m.group(2), int(m.group(3), 16)
        ty = decl.get(cls, {}).get(fld)
        if not ty: continue
        PRIM = {'float32': 'Single', 'float64': 'Double', 'int32': 'Int32', 'uint32': 'UInt32', 'int64': 'Int64', 'bool': 'Boolean', 'uint8': 'Byte', 'int16': 'Int16', 'char': 'Char', 'string': 'String'}
        am = re.search(r'(?:class\s+|valuetype\s+)?(?:\[[^\]]+\])?([\w.`/+]+)(?:<[^>]*>)?\[\]\s*$', ty)
        if am:   # an array (of anything): its runtime type is "<Element>[]"
            el = am.group(1)
            exp = PRIM.get(el, re.split(r'[./+]', el)[-1]) + '[]'
        else:
            tm = re.search(r'class\s+(?:\[[^\]]+\])?([\w.`/+]+)', ty)
            if not tm:   # a value type: a number field, checked for a plausible value
                t = ty.split()[-1]
                kind = 1 if t == 'bool' else 2 if t == 'float32' else 4 if t.endswith('Microsoft.Xna.Framework.Vector2') else 0
                vm = re.search(r'valuetype\s+([\w.`/+]+)$', ty)
                if not kind and vm and list(enums.get(vm.group(1).replace('/', '+'), {})) == ['value__']: kind = 3
                if kind: rows.append((re.split(r'[.+]', cls)[-1], fld, off, t.split('.')[-1].split('/')[-1], f == 'translate.toml', kind))
                continue
            exp = re.split(r'[./+]', tm.group(1))[-1]
        rows.append((re.split(r'[.+]', cls)[-1], fld, off, exp, f == 'translate.toml', 0))
out = ['/* GENERATED by tools/tfex/state-fieldcheck.py: the TF.State measurement\'s pinned fields (class, field, offset, PC type, confirmed,',
       ' * kind: 0 a reference, 1 bool, 2 float32, 3 enum, 4 Vector2) */']
for c, f, o, e, confirmed, kind in sorted(set(rows)):
    out.append(f'{{"{c}", "{f}", {hex(o)}, "{e}", {"true" if confirmed else "false"}, {kind}}},')
open(os.path.join(here, '..', '..', 'hw-probe/exlaunch/source/program/tfex/runtime/tfexgen_state_fieldcheck.inc'), 'w').write('\n'.join(out) + '\n')
print(len(rows), 'fields:', sum(1 for r in rows if not r[5]), 'reference,', sum(1 for r in rows if r[5]), 'number')
