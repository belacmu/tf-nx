#!/usr/bin/env python3
"""statepins.py: step D of docs/tfstate-rollback-measurement.md. Writes tools/tfex/state-pins.toml from the layout database: for every
private field TF.State's units request (the f_ bindings of tfexgen_binding.hpp that reflection and translate.toml's confirmed pins don't
give), its offset from layoutdb.json (runtime slot maps), accessors.json (compiled accessors) or layoutpredict.json (the layout rule
between anchors), with the raw-byte verdict (rawverify.py on rawdump.tgz). A field the database doesn't place gets no pin: the
translator makes it a state gap (a dummy), never a guessed offset.

  statepins.py [raw dir]   (raw dir: the unpacked rawdump.tgz's raw/, for the verdicts)"""
import os, re, sys, json, collections
here = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, here)
import rtypes, layoutpredict as lp, rawverify as rv, rawcheck
root = os.path.join(here, '..', '..')

def main(argv):
    lay = lp.Layout(os.path.join(root, '.cache', 'towerfall-pc.il'))
    ldb = json.load(open(os.path.join(here, 'layoutdb.json')))['placed']
    acc = json.load(open(os.path.join(here, 'accessors.json')))
    pre = json.load(open(os.path.join(here, 'layoutpredict.json')))['placed']
    tt = open(os.path.join(root, 'tools/tfex/translate.toml')).read()
    conf = {f'{m.group(1)}.{m.group(2)}' for m in re.finditer(r'\[pin\."([\w.+`]+)\.(\w+)\(\)"\]\s*off = ', tt)}
    tab = rtypes.table()
    refl = {f'{c}.{n}' for c, t in tab.items() for n, o, a, ty in (t.fields or []) if o is not None}
    h = open(os.path.join(root, 'hw-probe/exlaunch/source/program/tfex/gen/tfexgen_binding.hpp')).read()
    used = sorted(set(re.findall(r'constexpr uint32_t f_\w+ = [^;]+;\s+/\* (?:UNRESOLVED )?([\w.+`]+\.\w+)', h)))
    recs = collections.defaultdict(list)
    if argv:
        stems = {}
        for c in lay.tab: stems.setdefault(re.sub(r'[^A-Za-z0-9_]', '_', re.split(r'[.+]', c)[-1]), c)
        for f in os.listdir(argv[0]):
            if f[:-4] in stems:
                rs, _ = rawcheck.records(os.path.join(argv[0], f)); c = stems[f[:-4]]
                while c and c in lay.tab: recs[c] += [r[3] for r in rs]; c = lay.tab[c].parent
    out = ['# GENERATED by tools/re/statepins.py (step D, docs/tfstate-rollback-measurement.md): the private game fields TF.State reads,',
           '# from the layout database (tools/re: layoutdb.json, accessors.json, layoutpredict.json). Not confirmed in the disassembly',
           '# (translate.toml [pin] holds confirmed ones). Read by the translator only for TF.State units\' requests (CodeGen); a field',
           '# not listed is a state gap (a dummy). "bytes": the raw-byte check (rawverify.py) on step B\'s dump.', '']
    cnt = collections.Counter(); missing = []
    for k in used:
        if k in refl or k in conf: continue
        c, n = k.rsplit('.', 1)
        it = dict(lay.decl.get(c, [])).get(n)
        if it is None: continue
        src = ('layoutdb.py: runtime slot maps', ldb) , ('accessors.py: the compiled accessor', acc), ('layoutpredict.py: the layout rule between anchors', pre)
        o, why = next(((d[k], w) for w, d in src if k in d), (None, None))
        if o is None: missing.append(k); continue
        verdict = 'unseen'
        ks = rv.kinds(lay, it)
        if recs.get(c):
            verdict = 'unchecked' if not ks else 'ok' if all(o + ro + sz <= len(r) and rv.plausible(kd, r[o + ro:o + ro + sz])
                                                             for r in recs[c] for ro, kd, sz in ks) else 'BAD'
        cnt[verdict] += 1
        out += [f'[pin."{k}()"]', f'off = {hex(o)}', f'why = "{why}; bytes: {verdict}"']
    open(os.path.join(root, 'tools/tfex/state-pins.toml'), 'w').write('\n'.join(out) + '\n')
    print(f'statepins: {sum(cnt.values())} pins ({dict(cnt)}); {len(missing)} fields not placed (gaps): {" ".join(m.replace("TowerFall.", "") for m in missing)}')

if __name__ == '__main__':
    main(sys.argv[1:])
