// translator fields-glue <tfex src> <out .cs> <cfg> <game type>...: TF.EX's reflection over a game struct's public fields
// (`typeof(T).GetFields(BindingFlags.Public | BindingFlags.Instance)`, as MatchStatsReport.BuildRawStats reads TowerFall.MatchStats),
// written as glue C# with one line per field in the type's metadata order (the order GetFields returns them). The Switch's runtime has
// no reflection the translator could call; the game's types don't change (the PC game gets no updates), so the list is fixed.
// A field of a struct type with fields of its own (MatchStats.Kills: KillStats) is read field by field as "<field>.<inner>", as
// BuildRawStats does; every value as Convert.ToDouble does (bool 1 / 0, the numbers widened).
using Microsoft.CodeAnalysis;
using System.Text;

namespace TfexTranslator;

sealed class FieldsGlueGen
{
    readonly Workspace ws;
    public FieldsGlueGen(Workspace ws) { this.ws = ws; }

    static IEnumerable<IFieldSymbol> PublicFields(INamedTypeSymbol t) =>
        t.GetMembers().OfType<IFieldSymbol>().Where(f => !f.IsStatic && f.DeclaredAccessibility == Accessibility.Public && !f.IsImplicitlyDeclared);

    static string Double(string x, ITypeSymbol t) => t.SpecialType == SpecialType.System_Boolean ? $"({x} ? 1.0 : 0.0)" : $"(double){x}";

    public int Run(string outFile, string[] types)
    {
        var sb = new StringBuilder();
        sb.Append("// GENERATED by tools/tfex/translator (fields-glue " + string.Join(" ", types) + "): TF.EX's reflection over game structs' public\n");
        sb.Append("// fields, one line per field in metadata order. Do not edit: re-run tools/tfex/translate.sh fields-glue <tag>.\n");
        var cls = Path.GetFileNameWithoutExtension(outFile);
        sb.Append($"using System.Collections.Generic;\n\nnamespace TfexGlue\n{{\n    public static class {cls}\n    {{\n");
        foreach (var spec in types)
        {
            // "<Type>:<FieldType>": the type's public instance fields of that type, by name, into a dictionary (FortRise's
            // patch_MatchVariants.StoreVanillaVariantsAsCustom: GetType().GetFields() where FieldType == typeof(Variant))
            // "<Type>:<FieldType>!<Field>,...": fields the Switch's game type lacks left out (the PC's MatchVariants.NoAutobalance)
            var skip = spec.Contains('!') ? spec[(spec.IndexOf('!') + 1)..].Split(',').ToHashSet() : new HashSet<string>();
            var specT = spec.Contains('!') ? spec[..spec.IndexOf('!')] : spec;
            if (specT.Split(':') is [var on, var fn])
            {
                var ot = ws.Compilation.GetTypeByMetadataName(on); var ft = ws.Compilation.GetTypeByMetadataName(fn);
                if (ot == null || ft == null) { Console.Error.WriteLine($"fields-glue: no type {on} or {fn}"); return 1; }
                var fs = PublicFields(ot).Where(f => SymbolEqualityComparer.Default.Equals(f.Type, ft) && !skip.Contains(f.Name)).ToList();
                sb.Append($"        // {on}'s public instance fields of type {fn}, by name, in metadata order: {fs.Count} entries" +
                          (skip.Count > 0 ? $" (not on the Switch's {ot.Name}: {string.Join(", ", skip)})" : "") + "\n");
                sb.Append($"        public static void {ft.Name}Fields_{ot.Name}(global::{on} v, Dictionary<string, global::{fn}> d)\n        {{\n");
                foreach (var f in fs) sb.Append($"            d.Add(\"{f.Name}\", v.{f.Name});\n");
                sb.Append("        }\n\n");
                continue;
            }
            var name = spec;
            var t = ws.Compilation.GetTypeByMetadataName(name);
            if (t == null) { Console.Error.WriteLine($"fields-glue: no type {name}"); return 1; }
            int n = 0;
            var body = new StringBuilder();
            foreach (var f in PublicFields(t))
            {
                if (f.Type is INamedTypeSymbol { TypeKind: TypeKind.Struct, SpecialType: SpecialType.None } inner && PublicFields(inner).Any())
                    foreach (var g in PublicFields(inner)) { body.Append($"            d[\"{f.Name}.{g.Name}\"] = {Double($"v.{f.Name}.{g.Name}", g.Type)};\n"); n++; }
                else { body.Append($"            d[\"{f.Name}\"] = {Double($"v.{f.Name}", f.Type)};\n"); n++; }
            }
            sb.Append($"        // typeof({name}).GetFields(Public | Instance), each value Convert.ToDouble'd: {n} entries\n");
            sb.Append($"        public static Dictionary<string, double> RawFields_{t.Name}(global::{name} v)\n        {{\n");
            sb.Append("            var d = new Dictionary<string, double>();\n").Append(body).Append("            return d;\n        }\n\n");
        }
        sb.Append("    }\n}\n");
        File.WriteAllText(outFile, sb.ToString());
        Console.Error.WriteLine($"fields-glue: {types.Length} types -> {outFile}");
        return 0;
    }
}
