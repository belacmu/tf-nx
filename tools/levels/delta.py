#!/usr/bin/env python3
"""delta.py [--check]: the PC versus levels as a delta over the Switch's own (docs/PLAN-TFNX-2026-11-04.md section 4), so a release needs no
PC game files: hw-probe/exlaunch/source/program/pclevels.gen.inc, compiled into the module (pclevels.cpp applies it on the console).

Online play needs the PC's levels (all 192 versus levels differ from the Switch's 1.4.1.6 ones: ChalicePads, events, chests, spawners...).
Per level, with line endings normalised (and a byte-order mark dropped): which lines of the Switch's file to keep, and the PC's lines in
place of the rest (about 2% of the PC's level text). A CRC-32 of the Switch file it was made from: a console whose file differs refuses it.
Every entry is checked here: the Switch level plus its delta is exactly the PC level's text.
  --check   exit 1 when pclevels.gen.inc is out of date
Sources (never in git: the game's files): the Switch romfs extract (XPLAY_SWITCH_ROMFS, default the roster tools' base extract) and the PC's
Content and DarkWorldContent (XPLAY_PC_CONTENT, default the browser's game files, as tools/pc-levels.sh)."""
import difflib, os, sys, zlib

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "hw-probe/exlaunch/source/program/pclevels.gen.inc")
SW = os.path.join(os.environ["XPLAY_SWITCH_ROMFS"], "Content/Levels/Versus")
PCC = os.environ.get("XPLAY_PC_CONTENT", os.path.expanduser("~/Code/Towerfall Browser/gamefiles/TowerFall/TowerFall.app/Contents/Resources/Content"))
PCDW = os.path.normpath(os.path.join(PCC, "..", "..", "..", "..", "DarkWorldContent"))


def text(p):
    b = open(p, "rb").read()
    if b.startswith(b"\xef\xbb\xbf"): b = b[3:]
    return b.replace(b"\r\n", b"\n").replace(b"\r", b"\n")


def lit(line):
    """a C string literal of these bytes (octal escapes: no hex run-on)"""
    out = []
    for c in line:
        ch = chr(c)
        out.append("\\\\" if ch == "\\" else '\\"' if ch == '"' else ch if 32 <= c < 127 else "\\%03o" % c)
    return "".join(out)


def apply(sw_lines, ops):
    out = []
    for op in ops:
        if op[0] == "=": out += sw_lines[op[1]:op[2]]
        else: out.append(op[1])
    return out


def build():
    for d in (SW, os.path.join(PCC, "Levels/Versus"), os.path.join(PCDW, "Levels/Versus")):
        if not os.path.isdir(d): sys.exit(f"pclevels: no {d}")
    rows, nlev, ins, maxlines, maxbytes = [], 0, 0, 0, 0
    for t in sorted(os.listdir(SW)):
        if not os.path.isdir(os.path.join(SW, t)): continue
        pcdir = os.path.join(PCDW if t[:2] in ("12", "13", "14", "15") else PCC, "Levels/Versus", t)
        for f in sorted(os.listdir(os.path.join(SW, t))):
            if not f.endswith(".oel") or f == "tb.oel": continue
            pc = os.path.join(pcdir, f)
            if not os.path.isfile(pc): sys.exit(f"pclevels: no PC level {pc}")
            s, p = text(os.path.join(SW, t, f)), text(pc)
            sl, pl = s.split(b"\n"), p.split(b"\n")
            ops = []
            for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, sl, pl, autojunk=False).get_opcodes():
                if tag == "equal": ops.append(("=", i1, i2))
                else: ops += [("+", x) for x in pl[j1:j2]]
            if b"\n".join(apply(sl, ops)) != p: sys.exit(f"pclevels: {t}/{f}: the delta doesn't rebuild the PC level")
            script = "".join(f"={a},{b}\\n" if k == "=" else "+" + lit(a) + "\\n" for k, a, *rest in [(o[0], o[1], *o[2:]) for o in ops]
                             for b in [rest[0] if rest else None])
            rows.append(f'    {{ "{t}/{f}", 0x{zlib.crc32(s):08x}u, {len(sl)}, {len(p)},\n      "{script}" }},')
            nlev += 1; ins += sum(1 for o in ops if o[0] == "+"); maxlines = max(maxlines, len(sl)); maxbytes = max(maxbytes, len(s), len(p))
    head = [f"/* GENERATED by tools/levels/delta.py from the Switch's and the PC's game files: do not edit. The PC's {nlev} versus levels as",
            f" * deltas over the Switch's own ({ins} PC lines in all); pclevels.cpp applies them. Per level: its path under Content/Levels/Versus,",
            " * the CRC-32 of the Switch file it was made from (normalised: no byte-order mark, '\\n' line ends), that file's line count, the PC",
            " * level's length, and the script: \"=a,b\" keeps the Switch file's lines a..b-1, \"+text\" adds a PC line. */",
            f"constexpr int kPcLevelCount = {nlev}, kPcLevelMaxLines = {maxlines}, kPcLevelMaxBytes = {maxbytes};",
            "const PcLevelDelta kPcLevels[] = {"]
    return "\n".join(head + rows + ["};", ""]), nlev, ins


def main():
    out, n, ins = build()
    if "--check" in sys.argv:
        ok = os.path.isfile(OUT) and open(OUT).read() == out
        print(f"pclevels: {'up to date' if ok else 'pclevels.gen.inc is out of date: run tools/levels/delta.py'} ({n} levels)")
        sys.exit(0 if ok else 1)
    open(OUT, "w").write(out)
    print(f"pclevels: {n} levels, {ins} PC lines -> {os.path.relpath(OUT, ROOT)} ({len(out) // 1024} KB), every one checked against the PC's")


main()
